"""Значки филиалов: буквы из номера ДФА, код региона с автономера и цвет филиала.

Ключи — короткие названия филиалов из core.excel_utils.BRANCH_MAPPING. Когда там
появляется новый филиал, добавьте его сюда; до этого он выводится текстом без значка.
"""

BRANCH_BADGES = {
    # филиал: (буквы как в ДФА, код региона, цвет)
    'Краснодар': ('КР', '23', '#e8891c'),
    'Москва': ('МСК', '77', '#c62f3a'),
    'Псков': ('ПС', '60', '#2f6fd6'),
    'Санкт-Петербург': ('СПБ', '78', '#6a4bc4'),  # в ДФА Петербурга буквенного кода нет
    'Мурманск': ('МН', '51', '#1aa3c4'),
    'Челябинск': ('ЧЛ', '74', '#5b6770'),
    'Великий Новгород': ('ВН', '53', '#b8860b'),
    'Архангельск': ('АР', '29', '#1f8a70'),
    'Казань': ('КЗ', '16', '#2f9e44'),
    'Нижний Новгород': ('НН', '52', '#d6336c'),
}


def branch_badge_data(branch):
    """{'letters', 'region', 'color'} для филиала или None, если значка нет."""
    if not branch:
        return None
    badge = BRANCH_BADGES.get(str(branch).strip())
    if badge is None:
        return None
    letters, region, color = badge
    return {'letters': letters, 'region': region, 'color': color}
